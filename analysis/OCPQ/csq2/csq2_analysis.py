#!/usr/bin/env python3
"""Reproduce CSQ2 from CSQ1 case-level data and raw OCPQ feature exports.

Required inputs
---------------
1. CSQ1 case-level CSV generated by `csq1_analysis.py`
   Required columns:
       requirement_id
       S3_days
       E2E_days

2. Requirement-modification OCPQ Situation Table
   Expected core columns:
       o1 = Requirement ID
       e1 = Modify Requirement event ID

3. Acceptance-rework OCPQ Situation Table
   Expected core columns:
       o1 = Requirement ID
       e1 = Perform Business And Technical Acceptance event ID
   The preserved query filters:
       e1.attr('decision') == 'ACCEPTANCE_REWORK'

4. Contract-review OCPQ Situation Table
   Expected core columns:
       o1 = Requirement ID
       e1 = Review Contract event ID

5. Requirement-Voucher mapping OCPQ export
   Expected core columns:
       o1 = Requirement ID
       o2 = Voucher ID
       e1 = Post Accounting Voucher event ID

6. Voucher-rework OCPQ export preserved for CSQ3
   Expected core columns:
       o1 = Voucher ID
       e1 = Modify Accounting Voucher event ID
       e2 = Post Accounting Voucher event ID

Feature-query exports are positive-occurrence tables. They are left-joined to
the complete 25-row CSQ1 posted-Requirement cohort. Missing feature counts are
set to zero.

Outputs
-------
intermediate/csq2_requirement_features.csv
intermediate/csq2_voucher_rework_mapping_crosscheck.csv
results/tables/table_4_10.csv
results/tables/table_4_11.csv
results/tables/csq2_summary_numeric.csv
results/csq2_run_summary.txt
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd


CSQ1_REQUIRED = {"requirement_id", "S3_days", "E2E_days"}
POSITIVE_REQUIRED = {"o1", "e1"}
MAPPING_REQUIRED = {"o1", "o2", "e1"}
VOUCHER_REWORK_REQUIRED = {"o1", "e1", "e2"}

EXPECTED_UPPER_TAIL = {
    "R-5",
    "R-6",
    "R-9",
    "R-10",
    "R-23",
    "R-25",
    "R-27",
}

EXPECTED_ACCEPTANCE_COUNTS = {
    "R-5": 1,
    "R-23": 2,
    "R-25": 3,
    "R-27": 1,
}

EXPECTED_VOUCHER_MAPPING = {
    "V-O-14": "R-16",
    "V-O-21": "R-24",
    "V-O-22": "R-25",
}


def parse_bool(value) -> bool:
    if isinstance(value, (bool, np.bool_)):
        return bool(value)
    if pd.isna(value):
        raise ValueError("Missing boolean value.")
    text = str(value).strip().lower()
    if text in {"true", "1", "yes", "y"}:
        return True
    if text in {"false", "0", "no", "n"}:
        return False
    raise ValueError(f"Cannot parse boolean value: {value!r}")


def filter_satisfied(df: pd.DataFrame) -> pd.DataFrame:
    if "Satisfied" not in df.columns:
        return df.copy()
    return df.loc[df["Satisfied"].map(parse_bool)].copy()


def require_columns(df: pd.DataFrame, required: set[str], label: str) -> None:
    missing = sorted(required - set(df.columns))
    if missing:
        raise ValueError(
            f"{label} is missing required columns: {', '.join(missing)}\n"
            f"Columns found: {', '.join(map(str, df.columns))}"
        )


def positive_counts(
    path: str | Path,
    feature_name: str,
) -> tuple[pd.Series, pd.DataFrame]:
    df = pd.read_csv(path)
    df = filter_satisfied(df)
    require_columns(df, POSITIVE_REQUIRED, feature_name)

    df["o1"] = df["o1"].astype(str)
    df["e1"] = df["e1"].astype(str)

    counts = df.groupby("o1", dropna=False).size().astype(int)
    counts.name = feature_name

    return counts, df


def percent_text(n: int, denom: int) -> str:
    pct = (n / denom * 100.0) if denom else float("nan")
    return f"{n} ({pct:.1f}%)"


def assert_rounded(actual: float, expected: float, label: str, ndigits: int = 2) -> None:
    actual_r = round(float(actual) + 1e-12, ndigits)
    if not np.isclose(actual_r, expected, atol=1e-9, rtol=0):
        raise AssertionError(
            f"Thesis checkpoint failed for {label}: "
            f"actual={actual:.10f}, reported={actual_r:.{ndigits}f}, "
            f"expected={expected:.{ndigits}f}."
        )


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Reproduce CSQ2 Tables 4.10 and 4.11."
    )
    parser.add_argument("csq1_case_level_csv")
    parser.add_argument("requirement_modification_csv")
    parser.add_argument("acceptance_rework_csv")
    parser.add_argument("contract_review_csv")
    parser.add_argument("requirement_voucher_mapping_csv")
    parser.add_argument("voucher_rework_csv")
    parser.add_argument("--out-dir", default=".")
    parser.add_argument(
        "--skip-checkpoints",
        action="store_true",
        help=(
            "Generate outputs without requiring equality to the current thesis baseline. "
            "Do not use for the formal baseline reproduction."
        ),
    )
    args = parser.parse_args()

    root = Path(args.out_dir)
    intermediate_dir = root / "intermediate"
    tables_dir = root / "results" / "tables"
    results_dir = root / "results"

    for d in [intermediate_dir, tables_dir, results_dir]:
        d.mkdir(parents=True, exist_ok=True)

    # ------------------------------------------------------------------
    # 1. Load the complete CSQ1 posted-Requirement cohort.
    # ------------------------------------------------------------------
    cohort = pd.read_csv(args.csq1_case_level_csv)
    require_columns(cohort, CSQ1_REQUIRED, "CSQ1 case-level CSV")

    if len(cohort) != 25:
        raise AssertionError(
            f"Expected 25 posted Requirements from CSQ1, found {len(cohort)}."
        )

    cohort["requirement_id"] = cohort["requirement_id"].astype(str)

    if cohort["requirement_id"].nunique() != 25:
        raise AssertionError("Expected 25 unique Requirement IDs in CSQ1 cohort.")

    for c in ["S3_days", "E2E_days"]:
        cohort[c] = pd.to_numeric(cohort[c], errors="raise")
        if cohort[c].isna().any():
            raise ValueError(f"Missing numeric value in {c}.")

    # Recompute P75 from full-precision CSQ1 E2E durations.
    p75 = float(
        cohort["E2E_days"].quantile(
            0.75,
            interpolation="linear",
        )
    )

    cohort["group"] = np.where(
        cohort["E2E_days"] >= p75,
        "upper-tail",
        "remaining",
    )

    upper_ids = set(
        cohort.loc[
            cohort["group"] == "upper-tail",
            "requirement_id",
        ]
    )

    n_upper = int((cohort["group"] == "upper-tail").sum())
    n_remaining = int((cohort["group"] == "remaining").sum())

    # ------------------------------------------------------------------
    # 2. Load positive occurrence tables.
    # ------------------------------------------------------------------
    mod_counts, mod_raw = positive_counts(
        args.requirement_modification_csv,
        "requirement_modification_count",
    )

    acceptance_counts, acceptance_raw = positive_counts(
        args.acceptance_rework_csv,
        "acceptance_rework_count",
    )

    contract_counts, contract_raw = positive_counts(
        args.contract_review_csv,
        "contract_review_count",
    )

    # ------------------------------------------------------------------
    # 3. Map voucher-rework occurrences back to Requirements.
    # ------------------------------------------------------------------
    mapping = pd.read_csv(args.requirement_voucher_mapping_csv)
    mapping = filter_satisfied(mapping)
    require_columns(
        mapping,
        MAPPING_REQUIRED,
        "Requirement-Voucher mapping CSV",
    )

    mapping = mapping.copy()
    mapping["o1"] = mapping["o1"].astype(str)  # Requirement
    mapping["o2"] = mapping["o2"].astype(str)  # Voucher
    mapping["e1"] = mapping["e1"].astype(str)  # Post event

    rework = pd.read_csv(args.voucher_rework_csv)
    rework = filter_satisfied(rework)
    require_columns(
        rework,
        VOUCHER_REWORK_REQUIRED,
        "Voucher-rework CSV",
    )

    rework = rework.copy()
    rework["o1"] = rework["o1"].astype(str)  # Voucher
    rework["e1"] = rework["e1"].astype(str)  # Modify event
    rework["e2"] = rework["e2"].astype(str)  # Post event

    voucher_cross = rework.merge(
        mapping,
        how="left",
        left_on=["o1", "e2"],
        right_on=["o2", "e1"],
        suffixes=("_rework", "_map"),
        validate="many_to_one",
        indicator=True,
    )

    if not (voucher_cross["_merge"] == "both").all():
        bad = voucher_cross.loc[
            voucher_cross["_merge"] != "both",
            ["o1_rework", "e2"],
        ]
        raise AssertionError(
            "At least one voucher-rework row could not be mapped to a Requirement "
            "using Voucher ID + Post Accounting Voucher event ID:\n"
            + bad.to_string(index=False)
        )

    voucher_cross = voucher_cross.rename(
        columns={
            "o1_rework": "voucher_id",
            "e1_rework": "modify_event_id",
            "e2": "post_event_id",
            "o1_map": "requirement_id",
        }
    )

    cross_output_columns = [
        "requirement_id",
        "voucher_id",
        "modify_event_id",
        "post_event_id",
    ]
    voucher_cross[cross_output_columns].to_csv(
        intermediate_dir / "csq2_voucher_rework_mapping_crosscheck.csv",
        index=False,
    )

    voucher_counts = (
        voucher_cross.groupby("requirement_id")
        .size()
        .astype(int)
    )
    voucher_counts.name = "voucher_rework_count"

    # ------------------------------------------------------------------
    # 4. Left-join all feature counts onto the 25-row cohort.
    # ------------------------------------------------------------------
    features = cohort[
        ["requirement_id", "S3_days", "E2E_days", "group"]
    ].copy()

    for counts in [
        mod_counts,
        acceptance_counts,
        contract_counts,
        voucher_counts,
    ]:
        features = features.merge(
            counts.rename_axis("requirement_id").reset_index(),
            how="left",
            on="requirement_id",
            validate="one_to_one",
        )

    count_columns = [
        "requirement_modification_count",
        "acceptance_rework_count",
        "contract_review_count",
        "voucher_rework_count",
    ]

    for c in count_columns:
        features[c] = features[c].fillna(0).astype(int)

    if len(features) != 25 or features["requirement_id"].nunique() != 25:
        raise AssertionError("Feature joining did not preserve the 25-row CSQ1 cohort.")

    features = features.sort_values(
        by=["group", "E2E_days", "requirement_id"],
        ascending=[True, False, True],
    )

    features.to_csv(
        intermediate_dir / "csq2_requirement_features.csv",
        index=False,
    )

    # ------------------------------------------------------------------
    # 5. Table 4.10.
    # ------------------------------------------------------------------
    upper = features.loc[features["group"] == "upper-tail"].copy()
    remaining = features.loc[features["group"] == "remaining"].copy()

    def group_feature_summary(df: pd.DataFrame) -> dict[str, float | int]:
        return {
            "N": int(len(df)),
            "median_e2e_days": float(df["E2E_days"].median()),
            "modification_n": int((df["requirement_modification_count"] >= 1).sum()),
            "acceptance_rework_n": int((df["acceptance_rework_count"] >= 1).sum()),
            "acceptance_rework_occurrences": int(df["acceptance_rework_count"].sum()),
            "contract_review_n": int((df["contract_review_count"] >= 1).sum()),
            "voucher_rework_n": int((df["voucher_rework_count"] >= 1).sum()),
        }

    upper_summary = group_feature_summary(upper)
    remaining_summary = group_feature_summary(remaining)

    table_410 = pd.DataFrame(
        [
            {
                "Characteristic": "Median E2E duration (calendar days)",
                f"Upper-tail (n={n_upper})": f"{upper_summary['median_e2e_days']:.2f}",
                f"Remaining (n={n_remaining})": f"{remaining_summary['median_e2e_days']:.2f}",
            },
            {
                "Characteristic": ">=1 Requirement modification",
                f"Upper-tail (n={n_upper})": percent_text(
                    upper_summary["modification_n"], n_upper
                ),
                f"Remaining (n={n_remaining})": percent_text(
                    remaining_summary["modification_n"], n_remaining
                ),
            },
            {
                "Characteristic": ">=1 acceptance rework",
                f"Upper-tail (n={n_upper})": percent_text(
                    upper_summary["acceptance_rework_n"], n_upper
                ),
                f"Remaining (n={n_remaining})": percent_text(
                    remaining_summary["acceptance_rework_n"], n_remaining
                ),
            },
            {
                "Characteristic": "Total acceptance-rework occurrences",
                f"Upper-tail (n={n_upper})": str(
                    upper_summary["acceptance_rework_occurrences"]
                ),
                f"Remaining (n={n_remaining})": str(
                    remaining_summary["acceptance_rework_occurrences"]
                ),
            },
            {
                "Characteristic": "Passed through Contract Review",
                f"Upper-tail (n={n_upper})": percent_text(
                    upper_summary["contract_review_n"], n_upper
                ),
                f"Remaining (n={n_remaining})": percent_text(
                    remaining_summary["contract_review_n"], n_remaining
                ),
            },
            {
                "Characteristic": ">=1 voucher rework",
                f"Upper-tail (n={n_upper})": percent_text(
                    upper_summary["voucher_rework_n"], n_upper
                ),
                f"Remaining (n={n_remaining})": percent_text(
                    remaining_summary["voucher_rework_n"], n_remaining
                ),
            },
        ]
    )
    table_410.to_csv(
        tables_dir / "table_4_10.csv",
        index=False,
    )

    # ------------------------------------------------------------------
    # 6. Table 4.11: acceptance-rework depth.
    # ------------------------------------------------------------------
    depth_rows = []
    for cycles in sorted(features["acceptance_rework_count"].unique()):
        g = features.loc[
            features["acceptance_rework_count"] == cycles
        ]
        depth_rows.append(
            {
                "Acceptance-rework cycles": int(cycles),
                "N": int(len(g)),
                "Mean S3 duration (calendar days)": f"{g['S3_days'].mean():.2f}",
                "Mean E2E duration (calendar days)": f"{g['E2E_days'].mean():.2f}",
            }
        )

    table_411 = pd.DataFrame(depth_rows)
    table_411.to_csv(
        tables_dir / "table_4_11.csv",
        index=False,
    )

    # ------------------------------------------------------------------
    # 7. Machine-readable numeric summary.
    # ------------------------------------------------------------------
    summary_numeric = pd.DataFrame(
        [
            {
                "p75_e2e_days": p75,
                "upper_tail_n": n_upper,
                "remaining_n": n_remaining,
                "upper_tail_median_e2e_days": upper_summary["median_e2e_days"],
                "remaining_median_e2e_days": remaining_summary["median_e2e_days"],
                "upper_tail_modification_n": upper_summary["modification_n"],
                "remaining_modification_n": remaining_summary["modification_n"],
                "upper_tail_acceptance_rework_n": upper_summary["acceptance_rework_n"],
                "remaining_acceptance_rework_n": remaining_summary["acceptance_rework_n"],
                "upper_tail_acceptance_rework_occurrences": upper_summary[
                    "acceptance_rework_occurrences"
                ],
                "remaining_acceptance_rework_occurrences": remaining_summary[
                    "acceptance_rework_occurrences"
                ],
                "upper_tail_contract_review_n": upper_summary["contract_review_n"],
                "remaining_contract_review_n": remaining_summary["contract_review_n"],
                "upper_tail_voucher_rework_n": upper_summary["voucher_rework_n"],
                "remaining_voucher_rework_n": remaining_summary["voucher_rework_n"],
            }
        ]
    )
    summary_numeric.to_csv(
        tables_dir / "csq2_summary_numeric.csv",
        index=False,
    )

    # ------------------------------------------------------------------
    # 8. Thesis baseline checkpoints.
    # ------------------------------------------------------------------
    checkpoint_status = "SKIPPED"

    if not args.skip_checkpoints:
        assert_rounded(p75, 19.30, "P75 E2E")
        if n_upper != 7 or n_remaining != 18:
            raise AssertionError(
                f"Expected 7 upper-tail and 18 remaining Requirements; "
                f"got {n_upper} and {n_remaining}."
            )

        if upper_ids != EXPECTED_UPPER_TAIL:
            raise AssertionError(
                "Upper-tail Requirement IDs differ from thesis baseline.\n"
                f"Actual: {sorted(upper_ids)}\n"
                f"Expected: {sorted(EXPECTED_UPPER_TAIL)}"
            )

        assert_rounded(
            upper_summary["median_e2e_days"],
            26.05,
            "upper-tail median E2E",
        )
        assert_rounded(
            remaining_summary["median_e2e_days"],
            17.71,
            "remaining median E2E",
        )

        expected_group_counts = {
            "upper_modification": 1,
            "remaining_modification": 1,
            "upper_acceptance_n": 4,
            "remaining_acceptance_n": 0,
            "upper_acceptance_occ": 7,
            "remaining_acceptance_occ": 0,
            "upper_contract": 3,
            "remaining_contract": 2,
            "upper_voucher": 1,
            "remaining_voucher": 2,
        }

        actual_group_counts = {
            "upper_modification": upper_summary["modification_n"],
            "remaining_modification": remaining_summary["modification_n"],
            "upper_acceptance_n": upper_summary["acceptance_rework_n"],
            "remaining_acceptance_n": remaining_summary["acceptance_rework_n"],
            "upper_acceptance_occ": upper_summary["acceptance_rework_occurrences"],
            "remaining_acceptance_occ": remaining_summary["acceptance_rework_occurrences"],
            "upper_contract": upper_summary["contract_review_n"],
            "remaining_contract": remaining_summary["contract_review_n"],
            "upper_voucher": upper_summary["voucher_rework_n"],
            "remaining_voucher": remaining_summary["voucher_rework_n"],
        }

        if actual_group_counts != expected_group_counts:
            raise AssertionError(
                "Table 4.10 feature-count checkpoints failed.\n"
                f"Actual: {actual_group_counts}\n"
                f"Expected: {expected_group_counts}"
            )

        actual_acceptance = (
            features.loc[
                features["acceptance_rework_count"] > 0,
                ["requirement_id", "acceptance_rework_count"],
            ]
            .set_index("requirement_id")["acceptance_rework_count"]
            .to_dict()
        )

        if actual_acceptance != EXPECTED_ACCEPTANCE_COUNTS:
            raise AssertionError(
                "Acceptance-rework depth by Requirement differs from baseline.\n"
                f"Actual: {actual_acceptance}\n"
                f"Expected: {EXPECTED_ACCEPTANCE_COUNTS}"
            )

        expected_depth = {
            0: (21, 7.23, 17.89),
            1: (2, 14.50, 26.13),
            2: (1, 21.92, 33.13),
            3: (1, 29.00, 38.31),
        }

        for cycles, (expected_n, expected_s3, expected_e2e) in expected_depth.items():
            g = features.loc[
                features["acceptance_rework_count"] == cycles
            ]
            if len(g) != expected_n:
                raise AssertionError(
                    f"Expected N={expected_n} for {cycles} acceptance-rework cycles, "
                    f"found {len(g)}."
                )
            assert_rounded(
                g["S3_days"].mean(),
                expected_s3,
                f"mean S3 for {cycles} rework cycles",
            )
            assert_rounded(
                g["E2E_days"].mean(),
                expected_e2e,
                f"mean E2E for {cycles} rework cycles",
            )

        r25 = features.loc[features["requirement_id"] == "R-25"]
        if len(r25) != 1:
            raise AssertionError("R-25 not found uniquely in CSQ1 cohort.")
        r25 = r25.iloc[0]
        if int(r25["acceptance_rework_count"]) != 3:
            raise AssertionError("R-25 should have 3 acceptance-rework occurrences.")
        assert_rounded(
            float(r25["E2E_days"]),
            38.31,
            "R-25 E2E",
        )

        actual_voucher_mapping = dict(
            zip(
                voucher_cross["voucher_id"],
                voucher_cross["requirement_id"],
            )
        )
        if actual_voucher_mapping != EXPECTED_VOUCHER_MAPPING:
            raise AssertionError(
                "Voucher-to-Requirement mapping differs from baseline.\n"
                f"Actual: {actual_voucher_mapping}\n"
                f"Expected: {EXPECTED_VOUCHER_MAPPING}"
            )

        checkpoint_status = "PASS"

    # ------------------------------------------------------------------
    # 9. Human-readable run summary.
    # ------------------------------------------------------------------
    raw_acceptance_count = int(len(acceptance_raw))
    raw_acceptance_requirements = int(acceptance_raw["o1"].nunique())
    raw_contract_requirements = int(contract_raw["o1"].nunique())
    raw_mod_requirements = int(mod_raw["o1"].nunique())

    lines = [
        "CSQ2 reproduction summary",
        "=========================",
        "",
        f"CSQ1 posted-Requirement cohort: {len(features)}",
        f"P75 E2E duration: {p75:.6f} calendar days",
        f"Upper-tail Requirements: {n_upper}",
        f"Remaining Requirements: {n_remaining}",
        "Upper-tail IDs: " + ", ".join(sorted(upper_ids)),
        "",
        "Raw OCPQ positive-result counts",
        "-------------------------------",
        f"Requirement modification: {len(mod_raw)} occurrences across {raw_mod_requirements} Requirements",
        f"Acceptance rework: {raw_acceptance_count} occurrences across {raw_acceptance_requirements} Requirements",
        f"Contract Review: {len(contract_raw)} occurrences across {raw_contract_requirements} Requirements",
        f"Voucher rework: {len(rework)} voucher lifecycles",
        "",
        "Posted-cohort feature comparison",
        "--------------------------------",
        f"Median E2E: upper-tail={upper_summary['median_e2e_days']:.6f}; "
        f"remaining={remaining_summary['median_e2e_days']:.6f}",
        f">=1 Requirement modification: upper-tail={upper_summary['modification_n']}/{n_upper}; "
        f"remaining={remaining_summary['modification_n']}/{n_remaining}",
        f">=1 acceptance rework: upper-tail={upper_summary['acceptance_rework_n']}/{n_upper}; "
        f"remaining={remaining_summary['acceptance_rework_n']}/{n_remaining}",
        f"Acceptance-rework occurrences: upper-tail={upper_summary['acceptance_rework_occurrences']}; "
        f"remaining={remaining_summary['acceptance_rework_occurrences']}",
        f"Passed through Contract Review: upper-tail={upper_summary['contract_review_n']}/{n_upper}; "
        f"remaining={remaining_summary['contract_review_n']}/{n_remaining}",
        f">=1 voucher rework: upper-tail={upper_summary['voucher_rework_n']}/{n_upper}; "
        f"remaining={remaining_summary['voucher_rework_n']}/{n_remaining}",
        "",
        "Acceptance-rework depth",
        "-----------------------",
    ]

    for cycles in sorted(features["acceptance_rework_count"].unique()):
        g = features.loc[
            features["acceptance_rework_count"] == cycles
        ]
        lines.append(
            f"{int(cycles)} cycles: N={len(g)}; "
            f"mean S3={g['S3_days'].mean():.6f}; "
            f"mean E2E={g['E2E_days'].mean():.6f}"
        )

    lines.extend(
        [
            "",
            "Voucher-rework Requirement mappings",
            "-----------------------------------",
        ]
    )

    for _, row in voucher_cross.sort_values("voucher_id").iterrows():
        lines.append(
            f"{row['voucher_id']} -> {row['requirement_id']} "
            f"(post event {row['post_event_id']})"
        )

    lines.extend(
        [
            "",
            f"Thesis checkpoint status: {checkpoint_status}",
        ]
    )

    summary_text = "\n".join(lines) + "\n"
    (results_dir / "csq2_run_summary.txt").write_text(
        summary_text,
        encoding="utf-8",
    )

    print(summary_text, end="")


if __name__ == "__main__":
    main()
