"""Generate four BQ4 thesis figures matching the supplied references.

Usage (from the package root):
    python script/generate_bq4_figures_from_excel.py --pm4py output/tables/BQ4_PM4Py_results.xlsx --ocpa output/OCPA/BQ4_OCPA_results.xlsx --out output/figures

Dependencies: pandas, numpy, matplotlib, openpyxl.
All observations come from Excel. Supplier_Rates must be generated by the
current bq4_pm4py_analysis.py; legacy supplier shares cannot replace rates.
Each chart is exported as 300-dpi PNG, editable SVG, and vector PDF.
"""

import argparse
import math
import textwrap
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.colors import LinearSegmentedColormap
from matplotlib.ticker import MultipleLocator
import numpy as np
import pandas as pd

BLUE = "#356489"
ORANGE = "#B86A30"
GRID = "#D4DEE7"
HEATMAP_CMAP = LinearSegmentedColormap.from_list(
    "thesis_blue", [(0.0, "#FFFFFF"), (0.2, "#EDF3F7"),
                    (0.48, "#B7CCDB"), (0.67, BLUE), (1.0, "#21435D")]
)
RESOURCE_ORDER = ["RR-1", "CR-1", "PO-1", "PO-2", "AT-1", "AA-1", "VR-1"]
ACTIVITY_ORDER = [
    "Review Requirement", "Review Contract", "Obtain Quotations",
    "Evaluate And Select Quotation", "Create Purchase Order",
    "Receive Contract Deliverable", "Perform Business And Technical Acceptance",
    "Verify Accounting Prerequisites", "Confirm Accounting Date",
    "Create Or Update Intangible Asset Record", "Create Accounting Voucher",
    "Modify Accounting Voucher", "Post Accounting Voucher", "Review Accounting Voucher",
]
# Display order and wrapping only; no data values are hardcoded.
WRAPPED_LABELS = {
    "Perform Business And Technical Acceptance": "Perform Business And Technical\nAcceptance",
    "Create Or Update Intangible Asset Record": "Create Or Update Intangible\nAsset Record",
    "Terminate After Contract Rejection": "Terminate After Contract\nRejection",
}


def configure_style():
    plt.rcParams.update({
        "font.family": "sans-serif", "font.sans-serif": ["Arial", "DejaVu Sans"],
        "font.size": 8, "axes.labelsize": 8, "xtick.labelsize": 7.5,
        "ytick.labelsize": 7.5, "legend.fontsize": 8,
        "figure.facecolor": "white", "axes.facecolor": "white",
        "savefig.facecolor": "white", "axes.edgecolor": "#777777",
        "axes.linewidth": 0.6, "text.color": "black", "axes.labelcolor": "black",
        "xtick.color": "black", "ytick.color": "black",
        "xtick.major.width": 0.5, "ytick.major.width": 0.5,
        "xtick.major.size": 3, "ytick.major.size": 3,
        "pdf.fonttype": 42, "svg.fonttype": "none",
    })


def read_sheet(path, sheet, columns):
    with pd.ExcelFile(path) as book:
        if sheet not in book.sheet_names:
            hint = (
                " Regenerate the workbook with the current bq4_pm4py_analysis.py. "
                "Legacy Supplier_Participation/Supplier_Selection shares use different denominators."
                if sheet == "Supplier_Rates" else ""
            )
            raise ValueError(f"{path.name}: missing worksheet '{sheet}'.{hint}")
        df = pd.read_excel(book, sheet_name=sheet)
    missing = set(columns) - set(df.columns)
    if missing:
        raise ValueError(f"{sheet}: missing columns {sorted(missing)}")
    if df.empty or df[list(columns)].isna().any().any():
        raise ValueError(f"{sheet}: empty table or missing required values")
    return df.copy()


def validate_numbers(df, columns, sheet, integer=False):
    for column in columns:
        df[column] = pd.to_numeric(df[column], errors="raise")
        values = df[column].to_numpy(dtype=float)
        if not np.isfinite(values).all() or (values < 0).any():
            raise ValueError(f"{sheet}.{column}: expected finite nonnegative values")
        if integer and not np.equal(values, np.floor(values)).all():
            raise ValueError(f"{sheet}.{column}: expected integer counts")


def load_tables(pm4py_file, ocpa_file):
    tables = {
        "workload": read_sheet(pm4py_file, "Resource_Workload", ["resource", "event_count"]),
        "activity": read_sheet(pm4py_file, "Resource_Activity", ["resource", "activity", "event_count"]),
        "rates": read_sheet(pm4py_file, "Supplier_Rates", [
            "supplier", "participation_count", "selection_count", "total_quotation_procedures",
            "participation_rate", "selection_rate",
        ]),
        "hotspots": read_sheet(ocpa_file, "07_activity_hotspots", [
            "activity", "multi_object_events", "mean_object_type_breadth",
        ]),
    }
    for key in ["workload", "activity"]:
        validate_numbers(tables[key], ["event_count"], key, integer=True)
    validate_numbers(tables["hotspots"], ["multi_object_events"], "hotspots", integer=True)
    validate_numbers(tables["hotspots"], ["mean_object_type_breadth"], "hotspots")
    rates = tables["rates"]
    validate_numbers(rates, ["participation_count", "selection_count", "total_quotation_procedures"], "Supplier_Rates", integer=True)
    validate_numbers(rates, ["participation_rate", "selection_rate"], "Supplier_Rates")
    total = rates["total_quotation_procedures"]
    if total.nunique() != 1 or (total <= 0).any():
        raise ValueError("Supplier_Rates: all suppliers must use the same positive quotation denominator")
    if rates["supplier"].duplicated().any():
        raise ValueError("Supplier_Rates: duplicate supplier rows")
    if (rates["selection_count"] > rates["participation_count"]).any() or (rates["participation_count"] > total).any():
        raise ValueError("Supplier_Rates: expected 0 <= selection_count <= participation_count <= total")
    for metric in ["participation", "selection"]:
        if not np.allclose(rates[f"{metric}_rate"], rates[f"{metric}_count"] / total, rtol=1e-7, atol=1e-9):
            raise ValueError(f"Supplier_Rates: inconsistent {metric} rate and denominator")
    return tables


def wrapped(activity, hotspot=False):
    if hotspot and activity == "Verify Accounting Prerequisites":
        return "Verify Accounting\nPrerequisites"
    return WRAPPED_LABELS.get(activity, textwrap.fill(activity, width=38, break_long_words=False))


def ordered_present(observed, preferred):
    # Additional categories in future workbooks remain visible.
    observed = set(observed)
    return [x for x in preferred if x in observed] + sorted(observed - set(preferred))


def horizontal_axes(ax):
    ax.spines[["top", "right"]].set_visible(False)
    ax.set_axisbelow(True)
    ax.grid(axis="x", color=GRID, linewidth=0.55)
    ax.tick_params(axis="y", pad=3)


def save_figure(fig, out_dir, stem, dpi=300):
    out_dir.mkdir(parents=True, exist_ok=True)
    # Fixed canvas preserves the reference aspect ratios in all formats.
    for extension in ["png", "svg", "pdf"]:
        target = out_dir / f"{stem}.{extension}"
        fig.savefig(target, dpi=dpi, facecolor="white")
        print(f"Saved: {target}")
    plt.close(fig)


def plot_resource_workload(df, out_dir, dpi=300):
    df = df.sort_values(["event_count", "resource"], ascending=[False, True], kind="stable")
    fig, ax = plt.subplots(figsize=(5.2, max(3.27, 0.35 * len(df) + 0.82)))
    fig.subplots_adjust(left=0.142, right=0.96, bottom=0.165, top=0.94)
    y = np.arange(len(df))
    bars = ax.barh(y, df["event_count"], height=0.65, color=BLUE)
    ax.set_yticks(y, df["resource"])
    ax.invert_yaxis()
    ax.set_xlabel("Number of logged events")
    ax.set_ylabel("Resource")
    maximum = float(df["event_count"].max())
    ax.set_xlim(0, max(145, maximum * 1.12))
    ax.xaxis.set_major_locator(MultipleLocator(20))
    horizontal_axes(ax)
    for bar, count in zip(bars, df["event_count"]):
        ax.annotate(str(int(count)), (bar.get_width(), bar.get_y() + bar.get_height() / 2),
                    xytext=(4, 0), textcoords="offset points", va="center", fontsize=8)
    save_figure(fig, out_dir, "BQ4_resource_workload", dpi)


def plot_resource_activity_heatmap(df, out_dir, dpi=300):
    pivot = df.pivot_table(index="activity", columns="resource", values="event_count", aggfunc="sum", fill_value=0)
    pivot = pivot.reindex(index=ordered_present(pivot.index, ACTIVITY_ORDER),
                          columns=ordered_present(pivot.columns, RESOURCE_ORDER))
    matrix = pivot.to_numpy(dtype=float)
    vmax = max(1, float(matrix.max()))
    fig, ax = plt.subplots(figsize=(max(5.24, 2.49 + 0.393 * len(pivot.columns)),
                                    max(5.14, 1.36 + 0.27 * len(pivot))))
    fig.subplots_adjust(left=0.433, right=0.96, top=0.882, bottom=0.15)
    im = ax.imshow(matrix, aspect="auto", cmap=HEATMAP_CMAP, vmin=0, vmax=vmax, interpolation="nearest")
    ax.set_xticks(np.arange(len(pivot.columns)), pivot.columns)
    ax.set_yticks(np.arange(len(pivot)), [wrapped(a) for a in pivot.index])
    ax.xaxis.tick_top()
    ax.xaxis.set_label_position("top")
    ax.set_xlabel("Resource", labelpad=10)
    ax.tick_params(axis="both", which="major", length=0, pad=5)
    ax.set_xticks(np.arange(-0.5, len(pivot.columns), 1), minor=True)
    ax.set_yticks(np.arange(-0.5, len(pivot), 1), minor=True)
    ax.grid(which="minor", color=GRID, linewidth=0.6)
    ax.tick_params(which="minor", length=0)
    for spine in ax.spines.values():
        spine.set_edgecolor(GRID)
    for i, j in np.ndindex(matrix.shape):
        value = matrix[i, j]
        if value:
            ax.text(j, i, str(int(value)), ha="center", va="center", fontsize=8.5,
                    color="white" if value >= vmax * 0.6 else "black")
    pos = ax.get_position()
    cax = fig.add_axes([pos.x0, 0.085, pos.width, 0.019])
    cbar = fig.colorbar(im, cax=cax, orientation="horizontal")
    step = max(1, 10 ** math.floor(math.log10(vmax)))
    cbar.set_ticks(list(np.arange(0, vmax, step)) + [vmax])
    cbar.set_label("Number of events", labelpad=3)
    cbar.ax.tick_params(labelsize=7, width=0.5)
    save_figure(fig, out_dir, "BQ4_resource_activity_heatmap", dpi)


def plot_supplier_participation_selection(df, out_dir, dpi=300):
    df = df.sort_values("supplier", kind="stable").reset_index(drop=True)
    fig, ax = plt.subplots(figsize=(5.2, max(4.0, 0.46 * len(df) + 1.24)))
    fig.subplots_adjust(left=0.13, right=0.98, bottom=0.165, top=0.88)
    y = np.arange(len(df))
    for metric, offset, color, label in [
        ("participation", -0.17, BLUE, "Participation rate"),
        ("selection", 0.17, ORANGE, "Selection rate"),
    ]:
        bars = ax.barh(y + offset, df[f"{metric}_rate"] * 100, height=0.30, color=color, label=label)
        for bar, count, total in zip(bars, df[f"{metric}_count"], df["total_quotation_procedures"]):
            ax.annotate(f"{bar.get_width():.1f}%  ({int(count)}/{int(total)})",
                        (bar.get_width(), bar.get_y() + bar.get_height() / 2), xytext=(4, 0),
                        textcoords="offset points", va="center", fontsize=7.2)
    ax.set_yticks(y, df["supplier"])
    ax.invert_yaxis()
    ax.set_ylabel("Supplier")
    ax.set_xlabel("Share of quotation procedures (%)")
    max_rate = float(df[["participation_rate", "selection_rate"]].max().max()) * 100
    ax.set_xlim(0, max(86, max_rate + 26))
    ax.xaxis.set_major_locator(MultipleLocator(10))
    ax.legend(loc="lower center", bbox_to_anchor=(0.5, 1.025), ncol=2, frameon=False,
              handlelength=1.9, columnspacing=1.8)
    horizontal_axes(ax)
    save_figure(fig, out_dir, "BQ4_supplier_participation_vs_selection", dpi)


def plot_activity_interaction_hotspots(df, out_dir, dpi=300):
    df = df.sort_values(["mean_object_type_breadth", "multi_object_events", "activity"],
                        ascending=[False, False, True], kind="stable")
    fig, ax = plt.subplots(figsize=(5.24, max(6.14, 0.32 * len(df) + 1.34)))
    fig.subplots_adjust(left=0.434, right=0.98, bottom=0.14, top=0.972)
    y = np.arange(len(df))
    bars = ax.barh(y, df["mean_object_type_breadth"], height=0.64, color=BLUE)
    ax.set_yticks(y, [wrapped(a, hotspot=True) for a in df["activity"]])
    ax.invert_yaxis()
    ax.set_xlabel("Mean number of business-object types\nper cross-object event")
    ax.set_xlim(0, max(8.4, float(df["mean_object_type_breadth"].max()) * 1.4))
    ax.xaxis.set_major_locator(MultipleLocator(1))
    horizontal_axes(ax)
    for bar, mean, count in zip(bars, df["mean_object_type_breadth"], df["multi_object_events"]):
        ax.annotate(f"{mean:.2f}  |  n={int(count)}",
                    (bar.get_width(), bar.get_y() + bar.get_height() / 2),
                    xytext=(3, 0), textcoords="offset points", va="center", fontsize=7.2)
    save_figure(fig, out_dir, "BQ4_activity_interaction_hotspots", dpi)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pm4py", required=True, type=Path, help="PM4Py workbook including Supplier_Rates")
    parser.add_argument("--ocpa", required=True, type=Path, help="OCPA workbook including 07_activity_hotspots")
    parser.add_argument("--out", default=Path("results/BQ4/figures"), type=Path)
    parser.add_argument("--dpi", default=300, type=int, help="PNG resolution (default: 300)")
    args = parser.parse_args()
    if args.dpi <= 0:
        parser.error("--dpi must be positive")
    for path in [args.pm4py, args.ocpa]:
        if not path.is_file():
            parser.error(f"Workbook not found: {path}")
    # Validate every input before creating figures or overwriting outputs.
    tables = load_tables(args.pm4py, args.ocpa)
    configure_style()
    plot_resource_workload(tables["workload"], args.out, args.dpi)
    plot_resource_activity_heatmap(tables["activity"], args.out, args.dpi)
    plot_supplier_participation_selection(tables["rates"], args.out, args.dpi)
    plot_activity_interaction_hotspots(tables["hotspots"], args.out, args.dpi)


if __name__ == "__main__":
    main()
